def t(key: str, lang: str = None, **kwargs) -> str:
    """
    Returns translation for given key.
    Falls back to English if key is missing in selected language.
    Supports template formatting via kwargs.
    """
    selected_lang = lang or get_current_language()
    lang_dict = TRANSLATIONS.get(selected_lang, TRANSLATIONS["en"])
    text = lang_dict.get(key)
    if text is None:
        text = TRANSLATIONS["en"].get(key, key)  
    if kwargs and isinstance(text, str):
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
